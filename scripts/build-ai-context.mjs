/* ── Vectors for semantic search ─────────────────────────────────────────
   Every passage search_site ranks (src/lib/aiPassages.ts), embedded with
   Gemini when GEMINI_API_KEY is set at build time, quantised to one signed
   byte per dimension with a scale per vector (about a quarter of the size
   of float32, and well within what ranking needs), and written to
   api/_vectors.ts as base64. Without a key, or if embedding fails, the
   module exports null and search stays keyword-only: a build never fails
   for want of vectors.

   Embedding is skipped when the passages are unchanged since the vectors
   already on disk were made (same digest, model and size), so a deploy
   that does not touch the data does not pay for it again. */

const VECTORS_OUT = path.join(process.cwd(), 'api', '_vectors.ts');
const EMBED_MODEL = process.env.GEMINI_EMBED_MODEL || 'gemini-embedding-2';
const EMBED_DIMS = 768;
const EMBED_BATCH = 20;
/* The free tier counts each text in a batch against a per-minute quota;
   a 429 waits and tries again rather than giving up on the first spike. */
const EMBED_RETRIES = 4;
const EMBED_RETRY_MS = 20_000;

function writeVectors(vectors, note) {
  const body = vectors
    ? `const VECTORS: { model: string; dims: number; count: number; digest: string; scales: number[]; data: string } | null = ${JSON.stringify(vectors)};`
    : `const VECTORS: { model: string; dims: number; count: number; digest: string; scales: number[]; data: string } | null = null;`;
  fs.writeFileSync(
    VECTORS_OUT,
    `// Generated by scripts/build-ai-context.mjs. Do not edit.\n// ${note}\n\n${body}\n\nexport default VECTORS;\n`,
    'utf8'
  );
}

async function existingVectors() {
  try {
    const source = fs.readFileSync(VECTORS_OUT, 'utf8');
    const match = source.match(/= (\{"model".*\});$/m);
    return match ? JSON.parse(match[1]) : null;
  } catch {
    return null;
  }
}

async function embedBatch(key, texts, attempt = 0) {
  const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${EMBED_MODEL}:batchEmbedContents`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'X-goog-api-key': key },
    body: JSON.stringify({
      requests: texts.map((text) => ({
        model: `models/${EMBED_MODEL}`,
        content: { parts: [{ text }] },
        output_dimensionality: EMBED_DIMS,
      })),
    }),
    signal: AbortSignal.timeout(30_000),
  });
  if (response.status === 429 && attempt < EMBED_RETRIES) {
    await new Promise((resolve) => setTimeout(resolve, EMBED_RETRY_MS));
    return embedBatch(key, texts, attempt + 1);
  }
  if (!response.ok) throw new Error(`${response.status} ${(await response.text()).slice(0, 200)}`);
  const body = await response.json();
  const out = (body.embeddings ?? []).map((e) => e.values);
  if (out.length !== texts.length || out.some((v) => !Array.isArray(v) || v.length !== EMBED_DIMS)) {
    throw new Error('unexpected embedding response shape');
  }
  return out;
}

function quantise(vectors) {
  const bytes = new Int8Array(vectors.length * EMBED_DIMS);
  const scales = vectors.map((values, v) => {
    const norm = Math.hypot(...values) || 1;
    const unit = values.map((x) => x / norm);
    const max = Math.max(...unit.map(Math.abs)) || 1;
    const scale = max / 127;
    unit.forEach((x, d) => (bytes[v * EMBED_DIMS + d] = Math.round(x / scale)));
    return Number(scale.toPrecision(6));
  });
  return { scales, data: Buffer.from(bytes.buffer).toString('base64') };
}

const passages = buildPassages(PROJECTS, EXPERIENCE);
const passageDigest = passagesDigest(passages);
const embedKey = process.env.GEMINI_API_KEY;

const previous = await existingVectors();
const current = previous && previous.digest === passageDigest && previous.model === EMBED_MODEL && previous.dims === EMBED_DIMS;

if (!embedKey) {
  // Vectors already on disk for exactly these passages stay valid without a key.
  if (current) {
    console.log(`ai vectors: no GEMINI_API_KEY, kept the vectors on disk (they match all ${passages.length} passages)`);
  } else {
    writeVectors(null, 'Built without GEMINI_API_KEY: no vectors, so search is keyword-only.');
    console.log(`ai vectors: no GEMINI_API_KEY, keyword search only (${passages.length} passages)`);
  }
} else {
  if (current) {
    console.log(`ai vectors: unchanged, kept (${passages.length} passages)`);
  } else {
    try {
      const vectors = [];
      for (let i = 0; i < passages.length; i += EMBED_BATCH) {
        vectors.push(...(await embedBatch(embedKey, passages.slice(i, i + EMBED_BATCH).map(passageDocument))));
      }
      const { scales, data } = quantise(vectors);
      writeVectors(
        { model: EMBED_MODEL, dims: EMBED_DIMS, count: passages.length, digest: passageDigest, scales, data },
        `${passages.length} passages × ${EMBED_DIMS} dims, int8 with a scale per vector.`
      );
      console.log(`ai vectors: ${passages.length} passages embedded with ${EMBED_MODEL} → api/_vectors.ts (${(data.length / 1024).toFixed(0)} KB base64)`);
    } catch (error) {
      writeVectors(null, `Embedding failed at build time; search is keyword-only until the next build.`);
      console.warn(`ai vectors: embedding failed (${error instanceof Error ? error.message : error}); keyword search only`);
    }
  }
}
